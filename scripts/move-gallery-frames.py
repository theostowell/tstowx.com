#!/usr/bin/env python3
"""Move frames from one gallery to another.

Used to lift the three panda frames out of `street` and into `wildlife`: they came in with the
Hong Kong project but they are animal photographs, not street ones. Rebakes from the original
JPEGs on the photo site, uploads under the destination gallery with the next free numbers,
deletes the old objects, and rewrites data/galleries.yaml.
"""

from __future__ import annotations

import os
import pathlib
import subprocess
import sys

from PIL import Image

REPO = pathlib.Path("/root/tstowx.com")
PROJECT = pathlib.Path("/root/photos.tstowx.com/content/projects/HKG, MAC + CHN")
STAGE = pathlib.Path("/root/.hermes/cache/scratch/gallery-move")
BUCKET = "R2:tstowx-images"
ZONE_ID = "51a003f157fe4c246e967a90db57a4f9"
MAX_EDGE = 1600
QUALITY = 82

# Source JPEG -> (from gallery, from file) — sorted order of the project, as build-galleries.py did.
MOVES = [
    ("IMG_0044.jpg", "street", "street-001.webp"),
    ("IMG_0054.jpg", "street", "street-002.webp"),
    ("IMG_0057.jpg", "street", "street-003.webp"),
]
DEST = "wildlife"


def env() -> dict:
    vals = {}
    for line in pathlib.Path("/root/.config/r2/tstowx-images.env").read_text().splitlines():
        line = line.strip()
        if line and not line.startswith("#") and "=" in line:
            k, v = line.split("=", 1)
            vals[k.strip()] = v.strip().strip('"').strip("'")
    e = dict(os.environ)
    e.update({
        "RCLONE_CONFIG_R2_TYPE": "s3",
        "RCLONE_CONFIG_R2_PROVIDER": "Cloudflare",
        "RCLONE_CONFIG_R2_ACCESS_KEY_ID": vals["AWS_ACCESS_KEY_ID"],
        "RCLONE_CONFIG_R2_SECRET_ACCESS_KEY": vals["AWS_SECRET_ACCESS_KEY"],
        "RCLONE_CONFIG_R2_ENDPOINT": vals["R2_ENDPOINT"],
        "RCLONE_CONFIG_R2_ACL": "private",
        "RCLONE_CONFIG_R2_NO_CHECK_BUCKET": "true",
    })
    return e


def load_yaml(path: pathlib.Path) -> dict:
    """Tiny reader for the flat shape data/galleries.yaml uses."""
    out: dict[str, dict] = {}
    current = None
    for raw in path.read_text().splitlines():
        line = raw.rstrip()
        if not line.strip() or line.lstrip().startswith("#"):
            continue
        if not line.startswith(" "):
            current = line.rstrip(":")
            out[current] = {"card": None, "files": []}
        elif current:
            s = line.strip()
            if s.startswith("card:"):
                out[current]["card"] = s.split(":", 1)[1].strip()
            elif s.startswith("- name:"):
                out[current]["files"].append({"name": s.split(":", 1)[1].strip()})
            elif s.startswith("w:"):
                out[current]["files"][-1]["w"] = int(s.split(":", 1)[1])
            elif s.startswith("h:"):
                out[current]["files"][-1]["h"] = int(s.split(":", 1)[1])
    return out


def dump_yaml(path: pathlib.Path, data: dict) -> None:
    lines = ["# Generated by the gallery scripts — image dimensions for the justified grid.",
             "# Images serve from https://cdn.tstowx.com/galleries/<gallery>/<file>."]
    for g, info in data.items():
        lines.append(f"{g}:")
        if info.get("card"):
            lines.append(f"  card: {info['card']}")
        lines.append("  files:")
        for f in info["files"]:
            lines.append(f"    - name: {f['name']}")
            lines.append(f"      w: {f['w']}")
            lines.append(f"      h: {f['h']}")
    path.write_text("\n".join(lines) + "\n")


def main() -> int:
    STAGE.mkdir(parents=True, exist_ok=True)
    data_path = REPO / "data/galleries.yaml"
    data = load_yaml(data_path)

    moving = {f for _, _, f in MOVES}
    print(f"{DEST}: {len(data[DEST]['files'])} before")
    print(f"street: {len(data['street']['files'])} before")

    # Next free number in the destination.
    nums = [int(n["name"].split("-")[-1].split(".")[0]) for n in data[DEST]["files"]]
    nxt = max(nums) + 1

    made = []
    for src_name, from_g, from_f in MOVES:
        out_name = f"wildlife-{nxt:03d}.webp"
        nxt += 1
        with Image.open(PROJECT / src_name) as im:
            im = im.convert("RGB")
            im.thumbnail((MAX_EDGE, MAX_EDGE), Image.LANCZOS)
            w, h = im.size
            out = STAGE / out_name
            im.save(out, "WEBP", quality=QUALITY, method=6)
        made.append({"name": out_name, "w": w, "h": h, "bytes": out.stat().st_size,
                     "from": from_f, "gallery": from_g, "src": src_name})
        print(f"{src_name} -> {out_name} ({w}x{h}, {out.stat().st_size} bytes)")

    e = env()
    up = subprocess.run(["rclone", "copy", str(STAGE), f"{BUCKET}/galleries/{DEST}",
                         "--include", "*.webp", "--stats", "0", "--log-level", "ERROR"],
                        env=e, capture_output=True, text=True)
    print(f"upload: exit={up.returncode} {up.stderr.strip()[:200]}")
    if up.returncode:
        return 1

    remote = subprocess.run(["rclone", "lsf", "--format", "sp", f"{BUCKET}/galleries/{DEST}"],
                            env=e, capture_output=True, text=True).stdout
    sizes = {}
    for line in remote.splitlines():
        if ";" in line:
            size, path = line.split(";", 1)
            sizes[path] = int(size)
    bad = [m["name"] for m in made if sizes.get(m["name"]) != m["bytes"]]
    if bad:
        print("VERIFY FAILED:", bad)
        return 1
    print(f"verified {len(made)} uploads")

    # Remove the originals from the street gallery.
    for m in made:
        r = subprocess.run(["rclone", "deletefile", f"{BUCKET}/galleries/{m['gallery']}/{m['from']}"],
                           env=e, capture_output=True, text=True)
        print(f"deleted {m['gallery']}/{m['from']}: exit={r.returncode} {r.stderr.strip()[:120]}")

    # Rewrite the data file.
    data["street"]["files"] = [f for f in data["street"]["files"] if f["name"] not in moving]
    for m in made:
        data[DEST]["files"].append({"name": m["name"], "w": m["w"], "h": m["h"]})
    dump_yaml(data_path, data)
    print(f"{DEST}: {len(data[DEST]['files'])} after")
    print(f"street: {len(data['street']['files'])} after")

    # Purge the deleted URLs so the CDN stops handing them out.
    files = [f"https://cdn.tstowx.com/galleries/street/{m['from']}" for m in made]
    print("purge these URLs:", files)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
