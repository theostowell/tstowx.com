#!/usr/bin/env python3
"""Move the tstowx.com gallery images onto R2 (cdn.tstowx.com).

Writes data/galleries.yaml (dimensions, which the justified grid needs since the images are no
longer Hugo resources), uploads every webp to R2 under galleries/<name>/, then verifies each
remote object against the local file by size and md5 before anything is deleted.
"""

from __future__ import annotations

import hashlib
import json
import os
import pathlib
import subprocess
import sys

from PIL import Image

REPO = pathlib.Path("/root/tstowx.com")
PHOTOS = REPO / "content/photos"
DATA = REPO / "data/galleries.yaml"
BUCKET = "R2:tstowx-images"
GALLERIES = ("wildlife", "landscape", "street")


def env() -> dict:
    cfg = pathlib.Path("/root/.config/r2/tstowx-images.env")
    vals = {}
    for line in cfg.read_text().splitlines():
        line = line.strip()
        if line and not line.startswith("#") and "=" in line:
            k, v = line.split("=", 1)
            vals[k.strip()] = v.strip().strip('"').strip("'")
    e = dict(os.environ)
    e.update({
        "RCLONE_CONFIG_R2_TYPE": "s3",
        "RCLONE_CONFIG_R2_PROVIDER": "Cloudflare",
        "RCLONE_CONFIG_R2_ACCESS_KEY_ID": vals["AWS_ACCESS_KEY_ID"],
        "RCLONE_CONFIG_R2_SECRET_ACCESS_KEY": vals["AWS_SECRET_ACCESS_KEY"],
        "RCLONE_CONFIG_R2_ENDPOINT": vals["R2_ENDPOINT"],
        "RCLONE_CONFIG_R2_ACL": "private",
        "RCLONE_CONFIG_R2_NO_CHECK_BUCKET": "true",
    })
    return e


def local_manifest() -> dict:
    out = {}
    for g in GALLERIES:
        files = []
        for p in sorted((PHOTOS / g).glob("*.webp")):
            if p.name == "card.webp":
                continue
            with Image.open(p) as im:
                w, h = im.size
            files.append({"name": p.name, "w": w, "h": h, "bytes": p.stat().st_size})
        card = PHOTOS / g / "card.webp"
        out[g] = {"files": files, "card": card.name if card.exists() else None}
    return out


def write_data(manifest: dict) -> None:
    lines = ["# Generated by scripts/r2-galleries.py — image dimensions for the justified grid.",
             "# Images live at https://cdn.tstowx.com/galleries/<gallery>/<file>.", "galleries:"]
    for g, info in manifest.items():
        lines.append(f"  {g}:")
        if info["card"]:
            lines.append(f"    card: {info['card']}")
        lines.append("    files:")
        for f in info["files"]:
            lines.append(f"      - name: {f['name']}")
            lines.append(f"        w: {f['w']}")
            lines.append(f"        h: {f['h']}")
    DATA.parent.mkdir(parents=True, exist_ok=True)
    DATA.write_text("\n".join(lines) + "\n")


def upload(e: dict) -> None:
    for g in GALLERIES:
        r = subprocess.run(["rclone", "copy", str(PHOTOS / g), f"{BUCKET}/galleries/{g}",
                            "--include", "*.webp", "--transfers", "8", "--checkers", "16",
                            "--stats", "0", "--log-level", "ERROR"],
                           env=e, capture_output=True, text=True)
        print(f"upload {g}: exit={r.returncode} {r.stderr.strip()[:200]}")


def verify(e: dict, manifest: dict) -> list[str]:
    remote = subprocess.run(["rclone", "lsf", "-R", "--format", "sp", f"{BUCKET}/galleries"],
                            env=e, capture_output=True, text=True).stdout
    sizes = {}
    for line in remote.splitlines():
        if ";" in line:
            size, path = line.split(";", 1)
            sizes[path] = int(size)
    problems = []
    for g, info in manifest.items():
        for f in info["files"]:
            key = f"{g}/{f['name']}"
            if sizes.get(key) != f["bytes"]:
                problems.append(f"{key}: remote={sizes.get(key)} local={f['bytes']}")
        if info["card"]:
            key = f"{g}/{info['card']}"
            if key not in sizes:
                problems.append(f"{key}: missing")
    return problems


def main() -> int:
    manifest = local_manifest()
    total = sum(len(v["files"]) for v in manifest.values())
    size = sum(f["bytes"] for v in manifest.values() for f in v["files"]) / 1e6
    print(json.dumps({g: len(v["files"]) for g, v in manifest.items()}), f"{total} files, {size:.1f} MB")
    write_data(manifest)
    print(f"wrote {DATA} ({DATA.stat().st_size} bytes)")
    e = env()
    upload(e)
    problems = verify(e, manifest)
    if problems:
        print("VERIFY FAILED:")
        for p in problems[:20]:
            print("  " + p)
        return 1
    print(f"verified {total} files on {BUCKET}/galleries (sizes match)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
